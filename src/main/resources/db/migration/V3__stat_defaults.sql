-- Taupymo tikslų statistikos numatymai (F2 fazė, žr. docs/specs/taupymo-tikslai/spec.md 5 skyrius).
-- Viena bendra lentelė keliems skirtingiems "key" tipams (income / expenses / typical_amount), kiekvienas
-- segmentuotas atskirai pagal "segment" (namų ūkio dydis/dirbančiųjų skaičius arba tikslo tipas).
--
-- PASTABA: planinis automatinis atnaujinimo job'as (traukia VDA/Lietuvos banko duomenis) NĖRA MVP dalis,
-- bet lentelė suprojektuota taip, kad jį būtų galima pridėti vėliau be schemos pakeitimų – pakaktų
-- periodiškai paleidžiamo UPSERT (ON CONFLICT (key, segment) DO UPDATE), kuris atnaujintų value/source/
-- source_url/as_of ir paliktų is_illustrative = false naujai patvirtintoms reikšmėms.
--
-- annualInflation/annualReturn (prielaidos, ne statistika) SĄMONINGAI čia nededamos – F1 PR (#22, žr.
-- eu.atsidek.goals.GoalsEngine) jas jau įgyvendino kaip kodo konstantas su origin=ASSUMPTION
-- (PLAN.md K5 sprendimas: "nededami į stat_defaults iš viso"). Šis StatDefaultsService PR tą patį
-- sprendimą kartoja (duomenys nekuriami antrą kartą), tik grąžina tas pačias reikšmes atsakyme.
CREATE TABLE IF NOT EXISTS stat_defaults (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    key VARCHAR(40) NOT NULL,              -- pvz. 'income', 'expenses', 'typical_amount'
    segment VARCHAR(100) NOT NULL,         -- pvz. 'members=4;workers=2' arba 'goalType=CHILD'
    value NUMERIC(14,2) NOT NULL,
    unit VARCHAR(20) NOT NULL,             -- pvz. 'EUR_PER_MONTH', 'EUR'
    source VARCHAR(300) NOT NULL,
    source_url VARCHAR(500),
    as_of DATE,                            -- NULL, kai reikšmė iliustracinė ir neturi realios duomenų datos
    is_illustrative BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_stat_defaults_key_segment UNIQUE (key, segment)
);
