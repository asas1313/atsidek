import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;

/**
 * Perkelia duomenis iš seno H2 failo (prieš F0 fazę) į naują PostgreSQL (po F0, kai Flyway V1/V2
 * migracijos JAU sukūrė tuščias lenteles). Vienkartinis, rankomis vykdomas įrankis – žr.
 * deploy/migrate-h2-to-postgres.sh ir DEPLOY.md.
 *
 * SVARBU: šis klasė NIEKADA nevykdoma automatiškai (CI/deploy.sh jos nekviečia). Vykdo žmogus,
 * rankomis, su tiesiogine prieiga prie serverio/tinklo.
 *
 * Naudojimas (argumentai arba atitinkami ENV kintamieji):
 *   java -cp h2.jar:postgresql.jar:. Migrate \
 *     <h2JdbcUrl> <h2User> <h2Password> <pgJdbcUrl> <pgUser> <pgPassword>
 *
 * Elgsena:
 *  - Kopijuoja visas eilutes iš penkių lentelių (bank_account, statement_import, bank_transaction,
 *    classification_rule, user_setting) tiksliai tokia tvarka, kad nebūtų nuorodų į dar
 *    neįkeltus id'us (nėra realių FK apribojimų duomenų bazėje, bet tvarka paliekama logiška).
 *  - IDENTITY stulpeliai (bank_account.id, bank_transaction.id, classification_rule.id) įterpiami
 *    su senomis reikšmėmis (GENERATED BY DEFAULT leidžia tai), po kopijavimo sekos (sequence)
 *    nustatomos į MAX(id)+1, kitaip naujos eilutės po migracijos susidurtų su PK konfliktu.
 *  - PASTABA apie V2__migrate_psd_settings.sql: ta Flyway migracija jau įvykdyta PRIEŠ šį
 *    importą (ant tuščios Postgres DB), todėl ji buvo no-op. Šis įrankis PO duomenų kopijavimo
 *    pakartoja TĄ PATĮ senų psd_from/psd_to raktų perrašymą į psd_from_2026/psd_to_2026, kad
 *    duomenys liktų nuoseklūs su V2 logika.
 */
public class Migrate {

    private static final String[] TABLES_IN_ORDER = {
        "bank_account", "statement_import", "bank_transaction", "classification_rule", "user_setting"
    };

    public static void main(String[] args) throws Exception {
        String h2Url = arg(args, 0, "H2_URL", null);
        String h2User = arg(args, 1, "H2_USER", "sa");
        String h2Password = arg(args, 2, "H2_PASSWORD", "");
        String pgUrl = arg(args, 3, "PG_URL", null);
        String pgUser = arg(args, 4, "PG_USER", null);
        String pgPassword = arg(args, 5, "PG_PASSWORD", null);

        if (h2Url == null || pgUrl == null || pgUser == null || pgPassword == null) {
            System.err.println("Naudojimas: java -cp h2.jar:postgresql.jar:. Migrate <h2JdbcUrl> <h2User> <h2Password> <pgJdbcUrl> <pgUser> <pgPassword>");
            System.err.println("(arba atitinkami ENV: H2_URL, H2_USER, H2_PASSWORD, PG_URL, PG_USER, PG_PASSWORD)");
            System.exit(2);
        }

        System.out.println("H2  šaltinis: " + h2Url);
        System.out.println("PG  paskirtis: " + pgUrl);

        try (Connection h2 = DriverManager.getConnection(h2Url, h2User, h2Password);
             Connection pg = DriverManager.getConnection(pgUrl, pgUser, pgPassword)) {

            pg.setAutoCommit(false);
            try {
                assertTargetTablesEmpty(pg);
                for (String table : TABLES_IN_ORDER) {
                    long copied = copyTable(h2, pg, table);
                    System.out.println("  " + table + ": nukopijuota " + copied + " eilučių");
                }
                fixSequence(pg, "bank_account", "id");
                fixSequence(pg, "bank_transaction", "id");
                fixSequence(pg, "classification_rule", "id");
                rewritePsdSettings(pg);
                pg.commit();
                System.out.println("OK: migracija baigta ir commit'inta.");
            } catch (Exception e) {
                pg.rollback();
                System.err.println("KLAIDA, rollback atliktas: " + e.getMessage());
                throw e;
            }
        }
    }

    /** Saugiklis: nesutepame jau turinčios duomenų paskirties DB (pvz. paleidus antrą kartą per klaidą). */
    private static void assertTargetTablesEmpty(Connection pg) throws SQLException {
        for (String table : TABLES_IN_ORDER) {
            try (Statement st = pg.createStatement();
                 ResultSet rs = st.executeQuery("SELECT COUNT(*) FROM " + table)) {
                rs.next();
                long count = rs.getLong(1);
                if (count > 0) {
                    throw new IllegalStateException("Paskirties lentelė '" + table + "' jau turi " + count
                        + " eilučių – migracija skirta TIK tuščiai, ką tik Flyway sukurtai DB. Sustabdau.");
                }
            }
        }
    }

    private static long copyTable(Connection h2, Connection pg, String table) throws SQLException {
        long count = 0;
        try (Statement src = h2.createStatement();
             ResultSet rs = src.executeQuery("SELECT * FROM " + table)) {
            int columnCount = rs.getMetaData().getColumnCount();
            StringBuilder cols = new StringBuilder();
            StringBuilder placeholders = new StringBuilder();
            for (int i = 1; i <= columnCount; i++) {
                if (i > 1) { cols.append(", "); placeholders.append(", "); }
                cols.append(rs.getMetaData().getColumnName(i));
                placeholders.append('?');
            }
            String insertSql = "INSERT INTO " + table + " (" + cols + ") VALUES (" + placeholders + ")";
            try (PreparedStatement ins = pg.prepareStatement(insertSql)) {
                while (rs.next()) {
                    for (int i = 1; i <= columnCount; i++) {
                        ins.setObject(i, rs.getObject(i));
                    }
                    ins.addBatch();
                    count++;
                    if (count % 500 == 0) {
                        ins.executeBatch();
                    }
                }
                ins.executeBatch();
            }
        }
        return count;
    }

    /** IDENTITY sekas (sequences) po rankinio id įterpimo reikia patraukti į priekį, kitaip kitas INSERT be id susidurs su PK konfliktu. */
    private static void fixSequence(Connection pg, String table, String idColumn) throws SQLException {
        try (Statement st = pg.createStatement()) {
            st.execute(
                "SELECT setval(pg_get_serial_sequence('" + table + "', '" + idColumn + "'), "
                + "COALESCE((SELECT MAX(" + idColumn + ") FROM " + table + "), 0) + 1, false)");
        }
    }

    /**
     * Tas pats perrašymas kaip V2__migrate_psd_settings.sql, pakartotas PO duomenų importo, nes
     * V2 migracija Flyway'aus jau įvykdyta ant tuščios DB (prieš šį importą) ir buvo no-op.
     */
    private static void rewritePsdSettings(Connection pg) throws SQLException {
        try (Statement st = pg.createStatement()) {
            st.executeUpdate(
                "INSERT INTO user_setting (user_id, setting_key, setting_value) "
                + "SELECT user_id, 'psd_from_2026', setting_value FROM user_setting o WHERE setting_key = 'psd_from' "
                + "AND NOT EXISTS (SELECT 1 FROM user_setting n WHERE n.user_id = o.user_id AND n.setting_key = 'psd_from_2026')");
            st.executeUpdate(
                "INSERT INTO user_setting (user_id, setting_key, setting_value) "
                + "SELECT user_id, 'psd_to_2026', setting_value FROM user_setting o WHERE setting_key = 'psd_to' "
                + "AND NOT EXISTS (SELECT 1 FROM user_setting n WHERE n.user_id = o.user_id AND n.setting_key = 'psd_to_2026')");
            st.executeUpdate("DELETE FROM user_setting WHERE setting_key IN ('psd_from', 'psd_to')");
        }
    }

    /** args[index] laimi net jei tuščias (pvz. tyčia tuščias H2 slaptažodis); ENV/default – tik jei argumentas visai nepaduotas. */
    private static String arg(String[] args, int index, String envName, String defaultValue) {
        if (args.length > index) {
            return args[index];
        }
        String env = System.getenv(envName);
        return (env != null && !env.isBlank()) ? env : defaultValue;
    }
}
