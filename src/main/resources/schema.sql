CREATE TABLE IF NOT EXISTS bank_account (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id VARCHAR(64) NOT NULL,
    iban VARCHAR(34),
    iban_hash VARCHAR(64),
    label VARCHAR(100) NOT NULL,
    bank_name VARCHAR(50)
);

CREATE TABLE IF NOT EXISTS statement_import (
    id VARCHAR(36) PRIMARY KEY,
    user_id VARCHAR(64) NOT NULL,
    account_id BIGINT NOT NULL,
    source_format VARCHAR(30) NOT NULL,
    period_from DATE,
    period_to DATE,
    tx_count INT NOT NULL,
    created_at TIMESTAMP NOT NULL
);

CREATE TABLE IF NOT EXISTS bank_transaction (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id VARCHAR(64) NOT NULL,
    import_id VARCHAR(36) NOT NULL,
    account_id BIGINT NOT NULL,
    booking_date DATE NOT NULL,
    amount NUMERIC(14,2) NOT NULL,
    direction VARCHAR(3) NOT NULL,
    counterparty_name VARCHAR(300),
    counterparty_iban_hash VARCHAR(64),
    remittance VARCHAR(1000),
    dedup_key VARCHAR(64) NOT NULL,
    category VARCHAR(30),
    confidence NUMERIC(3,2),
    reason VARCHAR(300),
    confirmed BOOLEAN NOT NULL DEFAULT FALSE,
    rule_id BIGINT,
    CONSTRAINT uq_tx_dedup UNIQUE (user_id, dedup_key)
);
CREATE INDEX IF NOT EXISTS ix_tx_import ON bank_transaction (import_id);
CREATE INDEX IF NOT EXISTS ix_tx_user_date ON bank_transaction (user_id, booking_date);

CREATE TABLE IF NOT EXISTS classification_rule (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id VARCHAR(64) NOT NULL,
    match_type VARCHAR(12) NOT NULL,
    match_value VARCHAR(300) NOT NULL,
    display_name VARCHAR(300),
    category VARCHAR(30) NOT NULL,
    created_at TIMESTAMP NOT NULL
);
